// Copies the design tokens (single owner: docs/design/ux/tokens.json) into the app and
// generates the gluestack (UniWind / Tailwind v4) theme from them.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../../docs/design/ux/tokens.json', import.meta.url);
if (!existsSync(src)) {
  console.error('../docs/design/ux/tokens.json not found. Run from the superproject checkout.');
  process.exit(1);
}
copyFileSync(src, new URL('../src/theme/tokens.json', import.meta.url));
console.log('synced src/theme/tokens.json');

const t = JSON.parse(readFileSync(src, 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

// gluestack's generated components use shadcn-style semantic names; map them onto CAN tokens.
const alias = {
  background: 'bg',
  foreground: 'text',
  card: 'surface',
  'card-foreground': 'text',
  popover: 'surface',
  'popover-foreground': 'text',
  primary: 'primary',
  'primary-foreground': 'onPrimary',
  secondary: 'surfaceMuted',
  'secondary-foreground': 'text',
  muted: 'surfaceMuted',
  'muted-foreground': 'textMuted',
  accent: 'surfaceMuted',
  'accent-foreground': 'text',
  destructive: 'urgent',
  'destructive-foreground': 'onUrgent',
  border: 'border',
  input: 'controlBorder',
  ring: 'focus',
};

/** css var name -> value, per mode */
const vars = {};
for (const mode of ['light', 'dark']) {
  const { color, status } = t.themes[mode];
  const v = {};
  for (const [k, { value }] of Object.entries(color)) v[`--can-${kebab(k)}`] = value;
  for (const [s, { fg, bg }] of Object.entries(status)) {
    v[`--can-status-${s}-fg`] = fg;
    v[`--can-status-${s}-bg`] = bg;
  }
  for (const [a, k] of Object.entries(alias)) v[`--${a}`] = color[k].value;
  vars[mode] = v;
}

const header = 'generated by scripts/sync-tokens.mjs from docs/design/ux/tokens.json, do not edit';
writeFileSync(
  new URL('../src/theme/gluestack.generated.ts', import.meta.url),
  `// ${header}\nexport const gluestackTheme = ${JSON.stringify(vars, null, 2)} as const;\n`,
);

const block = (mode) =>
  Object.entries(vars[mode])
    .map(([k, val]) => `      ${k}: ${val};`)
    .join('\n');
const names = Object.keys(vars.light);
const colors = names.map((n) => `  --color-${n.slice(2)}: var(${n});`).join('\n');
const radii = Object.entries(t.radius)
  .map(([k, v]) => `  --radius-${k}: ${v}px;`)
  .join('\n');
const scale = Object.entries(t.type.scale)
  .map(
    ([k, s]) =>
      `  --text-${kebab(k)}: ${s.size}px;\n  --text-${kebab(k)}--line-height: ${s.line}px;\n  --text-${kebab(k)}--font-weight: ${s.weight};`,
  )
  .join('\n');
// Tailwind spacing base is 4px, equal to tokens space.1, so p-1..p-8 follow the token steps.
const css = `/* ${header} */
@import "tailwindcss";
@import 'uniwind';

@layer theme {
  :root {
    @variant light {
${block('light')}
    }

    @variant dark {
${block('dark')}
    }
  }
}

@theme inline {
${colors}
${radii}
${scale}
  --spacing: ${t.space['1']}px;
}
`;
writeFileSync(new URL('../global.css', import.meta.url), css);
console.log('generated global.css and src/theme/gluestack.generated.ts');
